#include "ssd1306.h"
#include <string.h>
#include "driver/i2c_master.h"

extern i2c_master_dev_handle_t ssd1306_dev_handle;
static uint8_t framebuffer[SSD1306_WIDTH * SSD1306_PAGES];

static bool write_commands(const uint8_t *cmds, size_t len)
{
    uint8_t packet[32] = {0};
    if (len > sizeof(packet) - 1) return false;
    memcpy(packet + 1, cmds, len);
    return i2c_master_transmit(ssd1306_dev_handle, packet, len + 1, 1000) == ESP_OK;
}

void ssd1306_clear(void)
{
    memset(framebuffer, 0, sizeof(framebuffer));
}

bool ssd1306_update(void)
{
    const uint8_t commands[] = {0x21, 0, 127, 0x22, 0, 7};
    if (!write_commands(commands, sizeof(commands))) return false;
    uint8_t packet[129];
    packet[0] = 0x40;
    for (unsigned page = 0; page < SSD1306_PAGES; page++) {
        memcpy(packet + 1, framebuffer + page * SSD1306_WIDTH, SSD1306_WIDTH);
        if (i2c_master_transmit(ssd1306_dev_handle, packet, sizeof(packet), 1000) != ESP_OK)
            return false;
    }
    return true;
}

bool ssd1306_init(void)
{
    const uint8_t commands[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0, 0x40,
        0x8D, 0x14, 0x20, 0, 0xA1, 0xC8, 0xDA, 0x12,
        0x81, 0x7F, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0x2E, 0xAF
    };
    if (!write_commands(commands, sizeof(commands))) return false;
    ssd1306_clear();
    return ssd1306_update();
}

