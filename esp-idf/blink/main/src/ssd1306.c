void ssd1306_draw_char(uint8_t x, uint8_t page, char c)
{
    if (x >= SSD1306_WIDTH || page >= SSD1306_PAGES) return;
    unsigned ch = (unsigned char)c;
    if (ch >= 128) ch = ' ';
    for (unsigned i = 0; i < 6 && x + i < SSD1306_WIDTH; i++)
        framebuffer[page * SSD1306_WIDTH + x + i] = i < 5 ? font[ch][i] : 0;
}

void ssd1306_draw_string(uint8_t x, uint8_t page, const char *str)
{
    if (!str || page >= SSD1306_PAGES) return;
    for (unsigned pos = x; *str && pos + 5 < SSD1306_WIDTH; pos += 6)
        ssd1306_draw_char((uint8_t)pos, page, *str++);
}
