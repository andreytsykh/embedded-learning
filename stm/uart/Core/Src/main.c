static void led_set(bool state)
{
    led_state = state;

    HAL_GPIO_WritePin(
        LED_GPIO_Port,
        LED_Pin,
        led_state ? GPIO_PIN_SET : GPIO_PIN_RESET
    );
}

static void led_toggle(void)
{
    led_set(!led_state);
}

static void uart_send_toggle_command(void)
{
    const uint8_t command = UART_COMMAND_TOGGLE_LED;

    (void)HAL_UART_Transmit(
        &huart2,
        &command,
        1U,
        100U
    );
}

static void uart_receive_process(void)
{
    uint8_t received_byte = 0U;

    const HAL_StatusTypeDef status =
        HAL_UART_Receive(
            &huart2,
            &received_byte,
            1U,
            0U
        );

    if (status != HAL_OK) {
        return;
    }

    if (received_byte == UART_COMMAND_TOGGLE_LED) {
        led_toggle();
    }
}

static void button_process(void)
{
    const GPIO_PinState current_raw_state =
        HAL_GPIO_ReadPin(
            BUTTON_GPIO_Port,
            BUTTON_Pin
        );

    const uint32_t current_time_ms =
        HAL_GetTick();

    if (current_raw_state != button_previous_raw_state) {
        button_previous_raw_state = current_raw_state;
        button_last_change_ms = current_time_ms;
    }

    if ((current_time_ms - button_last_change_ms) <
        BUTTON_DEBOUNCE_MS) {
        return;
    }

    if (current_raw_state == button_stable_state) {
        return;
    }

    button_stable_state = current_raw_state;

    if (button_stable_state == GPIO_PIN_SET) {
        uart_send_toggle_command();
    }
}


